const SESSION_COOKIE_NAMES = new Set([
	'SID',
	'SAPISID',
	'APISID',
	'__Secure-1PSID',
	'__Secure-3PSID'
]);

export function normalizeServerUrl(value) {
	const parsed = new URL(String(value || '').trim());
	if (!['http:', 'https:'].includes(parsed.protocol)) {
		throw new Error('Bili Sync 地址必须以 http:// 或 https:// 开头');
	}
	return parsed.origin;
}

export function permissionPattern(value) {
	const parsed = new URL(normalizeServerUrl(value));
	return `${parsed.protocol}//${parsed.hostname}/*`;
}

export function isYouTubeCookieDomain(domain) {
	const normalized = String(domain || '')
		.trim()
		.replace(/^\./, '')
		.toLowerCase();
	return (
		normalized === 'youtube.com' ||
		normalized.endsWith('.youtube.com') ||
		normalized === 'google.com' ||
		normalized.endsWith('.google.com')
	);
}

export function isDouyinCookieDomain(domain) {
	const normalized = String(domain || '')
		.trim()
		.replace(/^\./, '')
		.toLowerCase();
	return (
		normalized === 'douyin.com' ||
		normalized.endsWith('.douyin.com') ||
		normalized === 'bytedance.com' ||
		normalized.endsWith('.bytedance.com')
	);
}
export function isTikTokCookieDomain(domain) {
	const normalized = String(domain || '')
		.trim()
		.replace(/^\./, '')
		.toLowerCase();
	return (
		normalized === 'tiktok.com' ||
		normalized.endsWith('.tiktok.com') ||
		normalized === 'tiktokcdn.com' ||
		normalized.endsWith('.tiktokcdn.com')
	);
}

// 抖音「已登录」会话 Cookie：游客只会拿到 ttwid / UIFID / fpk 这类设备与风控 Cookie，
// 只有真正登录后才会出现下面这些字段。若只校验「有任何 douyin.com cookie」，游客导出也会
// 被当成登录成功，导入后所有需要登录的接口（作者作品、收藏夹、我的喜欢）都会失败。
const DOUYIN_SESSION_COOKIE_NAMES = new Set([
	'sessionid',
	'sessionid_ss',
	'sid_tt',
	'uid_tt',
	'uid_tt_ss',
	'sid_guard'
]);

const TIKTOK_SESSION_COOKIE_NAMES = new Set([
	'sessionid',
	'sessionid_ss',
	'sid_tt',
	'uid_tt',
	'passport_csrf_token',
	'ttwid'
]);


export function buildNetscapeCookies(cookies, platform = 'youtube') {
	const douyin = platform === 'douyin';
	const tiktok = platform === 'tiktok';
	const domainOk = (cookie) =>
		tiktok
			? isTikTokCookieDomain(cookie.domain)
			: douyin
				? isDouyinCookieDomain(cookie.domain)
				: isYouTubeCookieDomain(cookie.domain);
	const selected = (cookies || []).filter((cookie) => domainOk(cookie) && cookie.name);
	const hasSession =
		!tiktok && !douyin
			? selected.some((cookie) => SESSION_COOKIE_NAMES.has(cookie.name))
			: tiktok
				? selected.some((cookie) => TIKTOK_SESSION_COOKIE_NAMES.has(cookie.name))
				: selected.some((cookie) => DOUYIN_SESSION_COOKIE_NAMES.has(cookie.name));
	if (!hasSession) {
		const label = tiktok ? 'TikTok' : douyin ? '抖音' : 'YouTube';
		if (douyin) {
			throw new Error(
				'当前浏览器没有检测到 抖音 登录状态：只读到游客 Cookie，缺 sessionid / sid_tt / uid_tt。' +
					'请在已登录抖音的普通浏览器窗口里打开 douyin.com 再传输；无痕窗口、未登录的浏览器配置都不行'
			);
		}
		throw new Error(`当前浏览器没有检测到 ${label} 登录状态，请先在本浏览器打开并登录 ${label}`);
	}

	const lines = [
		'# Netscape HTTP Cookie File',
		'# Generated by Bili Sync Login Helper',
		'# Bili Sync Login Helper 1.5.3'
	];
	for (const cookie of selected) {
		const domain =
			cookie.domain || (tiktok ? '.tiktok.com' : douyin ? '.douyin.com' : '.youtube.com');
		const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
		const path = cookie.path || '/';
		const secure = cookie.secure ? 'TRUE' : 'FALSE';
		const expiry =
			Number.isFinite(cookie.expirationDate) && cookie.expirationDate > 0
				? Math.trunc(cookie.expirationDate)
				: 0;
		lines.push(
			[domain, includeSubdomains, path, secure, expiry, cookie.name, cookie.value || ''].join('\t')
		);
	}
	return `${lines.join('\n')}\n`;
}

export function responseMessage(payload, fallback) {
	if (payload && typeof payload.data === 'string' && payload.data.trim()) {
		return payload.data;
	}
	if (payload?.data && typeof payload.data.message === 'string') {
		return payload.data.message;
	}
	if (typeof payload?.message === 'string') {
		return payload.message;
	}
	return fallback;
}
