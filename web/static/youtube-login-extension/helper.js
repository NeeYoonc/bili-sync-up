const SESSION_COOKIE_NAMES = new Set([
	'SID',
	'SAPISID',
	'APISID',
	'__Secure-1PSID',
	'__Secure-3PSID'
]);

export function normalizeServerUrl(value) {
	const parsed = new URL(String(value || '').trim());
	if (!['http:', 'https:'].includes(parsed.protocol)) {
		throw new Error('Bili Sync 地址必须以 http:// 或 https:// 开头');
	}
	return parsed.origin;
}

export function permissionPattern(value) {
	const parsed = new URL(normalizeServerUrl(value));
	return `${parsed.protocol}//${parsed.hostname}/*`;
}

export function isYouTubeCookieDomain(domain) {
	const normalized = String(domain || '')
		.trim()
		.replace(/^\./, '')
		.toLowerCase();
	return normalized === 'youtube.com' || normalized.endsWith('.youtube.com');
}

export function isDouyinCookieDomain(domain) {
	const normalized = String(domain || '')
		.trim()
		.replace(/^\./, '')
		.toLowerCase();
	return (
		normalized === 'douyin.com' ||
		normalized.endsWith('.douyin.com') ||
		normalized === 'bytedance.com' ||
		normalized.endsWith('.bytedance.com')
	);
}

export function buildNetscapeCookies(cookies, platform = 'youtube') {
	const douyin = platform === 'douyin';
	const selected = (cookies || []).filter(
		(cookie) =>
			(douyin ? isDouyinCookieDomain(cookie.domain) : isYouTubeCookieDomain(cookie.domain)) &&
			cookie.name
	);
	if (
		douyin
			? selected.length === 0
			: !selected.some((cookie) => SESSION_COOKIE_NAMES.has(cookie.name))
	) {
		const label = douyin ? '抖音' : 'YouTube';
		throw new Error(`当前浏览器没有检测到 ${label} 登录状态，请先在本浏览器打开并登录 ${label}`);
	}

	const lines = ['# Netscape HTTP Cookie File', '# Generated by Bili Sync Login Helper'];
	for (const cookie of selected) {
		const domain = cookie.domain || (douyin ? '.douyin.com' : '.youtube.com');
		const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
		const path = cookie.path || '/';
		const secure = cookie.secure ? 'TRUE' : 'FALSE';
		const expiry =
			Number.isFinite(cookie.expirationDate) && cookie.expirationDate > 0
				? Math.trunc(cookie.expirationDate)
				: 0;
		lines.push(
			[domain, includeSubdomains, path, secure, expiry, cookie.name, cookie.value || ''].join('\t')
		);
	}
	return `${lines.join('\n')}\n`;
}

export function responseMessage(payload, fallback) {
	if (payload && typeof payload.data === 'string' && payload.data.trim()) {
		return payload.data;
	}
	if (payload?.data && typeof payload.data.message === 'string') {
		return payload.data.message;
	}
	if (typeof payload?.message === 'string') {
		return payload.message;
	}
	return fallback;
}
